using System;
using WhatsappApp.Protocol;
using WhatsappApp.Protocol.Client;
using WhatsappApp.Protocol.Signal;
using WhatsappApp.Protocol.WaProto;

namespace ProtocolTests
{
    /// <summary>
    /// The milestone's decisive test: the reference's own conversation, reproduced.
    ///
    /// Nothing about Signal can be checked by reasoning about it. A wrong info string, a
    /// DH pair in the wrong slot, a MAC over the wrong bytes, a counter that starts at one
    /// instead of zero, a version byte missing from the inner message - every one of those
    /// produces a session that works, decrypts its own messages, passes every round trip
    /// we could write, and is refused by WhatsApp. The only test that catches them is
    /// this one: the reference's keys, our arithmetic, and its own bytes.
    ///
    /// The plaintext is not the bare text either. The reference's suite encrypts a
    /// `PushMessageContent` protobuf with the body in it, padded with `0x80` and zeros to
    /// a multiple of 160 (see `pad` in its `SessionCipherTest.js`), and it is the padded
    /// bytes that the ciphertext covers. Both constructions are here, so the fixture's
    /// bytes can be compared and its plaintexts can be read.
    /// </summary>
    public static class SignalSessionTests
    {
        /// <summary>
        /// What the sender produces, byte for byte, against the reference's ciphertext.
        ///
        /// This one test covers the whole chain: the X3DH agreement (the root key), the
        /// first ratchet step, the chain's two HMACs, the message keys' HKDF, AES-CBC, the
        /// protobuf, the version byte and the eight-byte MAC. Any one of them wrong and the
        /// bytes differ.
        /// </summary>
        [Test]
        public static void WhatTheSenderProducesIsTheReferenceSCiphertext()
        {
            SessionRecord alice = Alice();

            // The reference's own transcript calls both of these `type: 3`, a pre-key
            // message, and the session says so before either is built - that flag is what
            // puts `type="pkmsg"` in the stanza, and the fixture's bytes carry the wrapper.
            Assert.IsTrue(alice.PreKeyPending);

            byte[] first = alice.Encrypt(PaddedBody(SignalFixture.Conversation.Plaintexts[0]));
            Assert.ByteArraysEqual(SignalFixture.Hex(SignalFixture.Conversation.Ciphertexts[0]), first);

            byte[] second = alice.Encrypt(PaddedBody(SignalFixture.Conversation.Plaintexts[1]));
            Assert.ByteArraysEqual(SignalFixture.Hex(SignalFixture.Conversation.Ciphertexts[1]), second);
        }

        /// <summary>
        /// And the plain message the sender produces after the step, which is the third
        /// message of the reference's transcript: no wrapper, so nothing about it is
        /// approximate. Its ratchet key is the one the sender's own step generated, so the
        /// bytes are hers and ours to compare - and they are the reference's.
        /// </summary>
        [Test]
        public static void WhatTheSenderProducesAfterTheStepIsTheReferenceSCiphertext()
        {
            SessionRecord alice = Alice();
            SessionRecord bob = Bob();

            // The receiver's half of the transcript, in order: the two messages she sent
            // before the reply, then the reply itself. Without them his session would be
            // stepping the ratchet from a root that had never moved, and the third message
            // would fail for a reason that has nothing to do with what is being checked.
            Deliver(alice, bob, SignalFixture.Conversation.Plaintexts[0]);
            Deliver(alice, bob, SignalFixture.Conversation.Plaintexts[1]);

            // The reply is what makes her step, and the step is what draws the key that
            // the reference drew at the same point in the same conversation: the key the
            // fixture hands her through `FixedRandom`, wearing her own name - her ratchet
            // key, generated by the step, not the senders' or the receivers'.
            Assert.AreEqual(SignalFixture.Conversation.ReceivedTexts[0],
                Body(alice.Decrypt(SignalFixture.Hex(SignalFixture.Conversation.Received[0]), false)));

            Assert.IsFalse(alice.PreKeyPending);

            // And now the third message of her transcript, plain rather than wrapped. Her
            // step is the fixture's - `AliceStepRatchetPrivate` is the key the reference's
            // step generated - so this one is the reference's own bytes too, and it is the
            // comparison that pins the *receiving* half of the ratchet: a step that derived
            // the wrong root or the wrong chain would send a message nobody could open.
            byte[] third = alice.Encrypt(PaddedBody(SignalFixture.Conversation.Plaintexts[2]));
            Assert.ByteArraysEqual(SignalFixture.Hex(SignalFixture.Conversation.Ciphertexts[2]), third);
            Assert.AreEqual(SignalFixture.Conversation.Plaintexts[2], Body(bob.Decrypt(third, false)));
        }

        /// <summary>
        /// Our reader on the reference's own bytes: the pre-key message's fields, and the
        /// inner message's, as the fixture carries them.
        /// </summary>
        [Test]
        public static void ThePreKeyMessageCarriesWhatTheReferenceCarries()
        {
            var envelope = PreKeySignalMessage.Decode(SignalEnvelope.Unwrap(FirstMessage()));

            Assert.AreEqual(SignalFixture.X3dh.BobPreKeyId, envelope.PreKeyId);
            Assert.IsTrue(envelope.HasPreKey);

            // The identity in the message is the *sender's* (Alice's), not the receiver's:
            // it is what the receiver uses to run its half of the agreement.
            Assert.ByteArraysEqual(X3dh.TypedPublicKey(SignalFixture.X3dh.AliceIdentityPrivate), envelope.IdentityKey);
            Assert.ByteArraysEqual(X3dh.TypedPublicKey(SignalFixture.X3dh.AliceBasePrivate), envelope.BaseKey);

            // The wrapper names the registration id of the device that sent it -
            // Alice's, not the receiver's - and the signed pre-key of the receiver's that
            // the agreement used. Both are in the reference's own bytes.
            Assert.AreEqual(SignalFixture.X3dh.AliceRegistrationId, envelope.RegistrationId);
            Assert.AreEqual(SignalFixture.X3dh.BobSignedPreKeyId, envelope.SignedPreKeyId);

            // The wrapped message is a whole message, its own version byte and MAC
            // included: the reference's own transcript is where that is visible.
            Assert.AreEqual(SignalConstants.MessageVersionByte, envelope.Message[0]);
            SignalMessage inner = SignalMessage.Decode(Shift(envelope.Message));
            Assert.ByteArraysEqual(X3dh.TypedPublicKey(SignalFixture.X3dh.AliceEphemeralPrivate), inner.EphemeralKey);
            Assert.AreEqual((uint)0, inner.Counter);
            Assert.AreEqual((uint)0, inner.PreviousCounter);
            Assert.AreEqual(160, inner.Ciphertext.Length);
        }

        /// <summary>
        /// And what the receiver opens, from the reference's bytes rather than ours: the
        /// first message is the pre-key one, which is where the agreement runs.
        /// </summary>
        [Test]
        public static void WhatTheReceiverOpensIsTheReferenceSText()
        {
            SessionRecord bob = Bob();

            string first = Body(bob.Decrypt(FirstMessage(), true));
            Assert.AreEqual(SignalFixture.BobSide.ReceivedTexts[0], first);

            // The second is a pre-key message too: she has had no reply yet, so both of her
            // first messages are wrapped and both stanzas say `type="pkmsg"`.
            string second = Body(bob.Decrypt(SignalFixture.Hex(SignalFixture.BobSide.Received[1]), true));
            Assert.AreEqual(SignalFixture.BobSide.ReceivedTexts[1], second);
        }

        /// <summary>
        /// The other direction: once the receiver has opened the first message, what he
        /// sends has to be the reference's bytes too. His first ratchet key is the one the
        /// fixture supplies - the key his own step generates - which is why the session is
        /// given a fixed source.
        /// </summary>
        [Test]
        public static void WhatTheReceiverSendsBackIsTheReferenceSCiphertext()
        {
            SessionRecord session = Bob();

            session.Decrypt(FirstMessage(), true);
            session.Decrypt(SignalFixture.Hex(SignalFixture.BobSide.Received[1]), true);

            byte[] reply = session.Encrypt(PaddedBody(SignalFixture.BobSide.Plaintexts[0]));
            Assert.ByteArraysEqual(SignalFixture.Hex(SignalFixture.BobSide.Ciphertexts[0]), reply);

            byte[] again = session.Encrypt(PaddedBody(SignalFixture.BobSide.Plaintexts[1]));
            Assert.ByteArraysEqual(SignalFixture.Hex(SignalFixture.BobSide.Ciphertexts[1]), again);
        }

        /// <summary>
        /// And the sender opens the reply: a new ratchet key arrives, so this is the step
        /// on the other side - the receiving chain derived from the message's own key,
        /// which is the half of the ratchet that can be checked without the reference's
        /// private halves.
        /// </summary>
        [Test]
        public static void TheSenderOpensTheReply()
        {
            SessionRecord alice = Alice();

            alice.Encrypt(PaddedBody("A"));
            alice.Encrypt(PaddedBody("B"));

            string reply = Body(alice.Decrypt(SignalFixture.Hex(SignalFixture.Conversation.Received[0]), false));
            Assert.AreEqual(SignalFixture.Conversation.ReceivedTexts[0], reply);
        }

        /// <summary>
        /// The two sessions complete a conversation after the step, which is the check
        /// that our own ratchet agrees with itself once keys have changed on both sides -
        /// and it goes further than the reference's own transcript does, so the two of them
        /// send with keys drawn fresh rather than with the fixture's single pair: a session
        /// that stepped onto the key it already had would be reusing a chain, and what this
        /// test would then be checking is a mistake (see `CounterRandom`).
        /// </summary>
        [Test]
        public static void TheConversationContinuesAfterTheStep()
        {
            SessionRecord alice = SignalSessions.Alice(new SignalSessions.CounterRandom());
            SessionRecord bob = SignalSessions.Bob(new SignalSessions.CounterRandom());

            Assert.AreEqual("A", Deliver(alice, bob, "A"));
            Assert.AreEqual("B", Deliver(alice, bob, "B"));

            // The reply makes the sender step the ratchet, and the messages after it are
            // read by the receiver's session - which by then holds two chains.
            Assert.AreEqual("C", Deliver(bob, alice, "C"));
            Assert.AreEqual("D", Deliver(alice, bob, "D"));
            Assert.AreEqual("E", Deliver(bob, alice, "E"));
        }

        /// <summary>
        /// A message that arrives before its predecessor is still readable: the skipped key
        /// is kept, and the gap can still be filled afterwards (review focus 1).
        /// </summary>
        [Test]
        public static void AMessageThatArrivesEarlyIsStillReadable()
        {
            SessionRecord alice = Alice();
            SessionRecord bob = Bob();

            bool preKey = alice.PreKeyPending;
            byte[] first = alice.Encrypt(PaddedBody("first"));
            byte[] second = alice.Encrypt(PaddedBody("second"));
            byte[] third = alice.Encrypt(PaddedBody("third"));

            Assert.AreEqual("first", Body(bob.Decrypt(first, preKey)));
            Assert.AreEqual("third", Body(bob.Decrypt(third, preKey)));
            Assert.AreEqual("second", Body(bob.Decrypt(second, preKey)));
        }

        /// <summary>
        /// The same message twice is refused rather than decrypted twice. The key it used
        /// is deleted, which is the reference's behaviour, and the duplicate is the app's
        /// to drop by message id - a test that asserted otherwise would pin a behaviour
        /// WhatsApp does not have.
        /// </summary>
        [Test]
        public static void AReplayedMessageIsRefused()
        {
            SessionRecord alice = Alice();
            SessionRecord bob = Bob();

            bool preKey = alice.PreKeyPending;
            byte[] message = alice.Encrypt(PaddedBody("once"));
            Assert.AreEqual("once", Body(bob.Decrypt(message, preKey)));

            Assert.Throws<ProtocolException>(delegate { bob.Decrypt(message, preKey); });
        }

        /// <summary>
        /// A message whose MAC no longer matches the bytes is refused before anything is
        /// decrypted, which is what the eight bytes are for.
        /// </summary>
        [Test]
        public static void ATamperedMessageIsRefused()
        {
            SessionRecord alice = Alice();
            SessionRecord bob = Bob();

            // His reply is what lets her send a plain message, and the last byte of a plain
            // message is its MAC - the right byte to move, because it is the one the
            // receiver checks before it looks at anything else.
            Deliver(alice, bob, "A");
            Deliver(bob, alice, "reply");

            byte[] plain = alice.Encrypt(PaddedBody("B"));
            Assert.IsFalse(alice.PreKeyPending);
            plain[plain.Length - 1] ^= 0x01;

            Assert.Throws<ProtocolException>(delegate { bob.Decrypt(plain, false); });
        }

        /// <summary>
        /// One message, delivered the way the client does it: the sender's session says
        /// which shape the message has (`PreKeyPending`), the stanza carries that as its
        /// `enc` type, and the receiver is told by it which path to take.
        /// </summary>
        private static string Deliver(SessionRecord from, SessionRecord to, string text)
        {
            bool preKey = from.PreKeyPending;

            return Body(to.Decrypt(from.Encrypt(PaddedBody(text)), preKey));
        }

        /// <summary>
        /// The sender's session with the *reference's* step key: the key her ratchet step
        /// draws is the one the reference drew, so the messages she sends after the step are
        /// the reference's bytes as well. That is the same bargain the private halves make -
        /// a fixture is not a phone, and a fixed key is the only way to compare.
        /// </summary>
        private static SessionRecord Alice()
        {
            return SignalSessions.Alice(new FixedRandom(SignalFixture.X3dh.AliceStepRatchetPrivate));
        }

        private static SessionRecord Bob()
        {
            return SignalSessions.Bob(new FixedRandom(SignalFixture.BobSide.SendingRatchetPrivate));
        }

        /// <summary>
        /// What the reference encrypts: a `PushMessageContent` with `body` set, padded the
        /// way its test suite pads it - `0x80` after the content, then zeros, to a length
        /// that is one less than a multiple of 160.
        /// </summary>
        private static byte[] PaddedBody(string text)
        {
            byte[] content = Content(text);
            var padded = new byte[PaddedLength(content.Length) - 1];

            Buffer.BlockCopy(content, 0, padded, 0, content.Length);
            padded[content.Length] = 0x80;

            return padded;
        }

        /// <summary>`PushMessageContent{ body: text }`: field 1, length-delimited.</summary>
        private static byte[] Content(string text)
        {
            byte[] body = System.Text.Encoding.UTF8.GetBytes(text);

            var writer = new ProtoWriter();
            writer.Bytes(1, body);

            return writer.ToArray();
        }

        /// <summary>The reference's `getPaddedMessageLength`, which counts the terminator twice.</summary>
        private static int PaddedLength(int contentLength)
        {
            int withTerminator = contentLength + 2;
            int parts = withTerminator / 160;
            if (withTerminator % 160 != 0) parts++;

            return parts * 160;
        }

        /// <summary>The body of a decrypted message: strip the padding, then read field 1.</summary>
        private static string Body(byte[] decrypted)
        {
            int end = -1;
            for (int i = 0; i < decrypted.Length; i++)
            {
                if (decrypted[i] == 0x80)
                {
                    end = i;
                    break;
                }

                if (decrypted[i] != 0x00 && end < 0 && i == 0 && decrypted[i] != 0x0a)
                {
                    throw new ProtocolException("the plaintext does not start with field 1");
                }
            }

            if (end < 0) throw new ProtocolException("the plaintext has no padding terminator");

            for (int i = end + 1; i < decrypted.Length; i++)
            {
                if (decrypted[i] != 0x00) throw new ProtocolException("the padding is not zeros");
            }

            var content = new byte[end];
            Buffer.BlockCopy(decrypted, 0, content, 0, end);

            var reader = new ProtoReader(content);
            while (reader.HasMore)
            {
                ProtoField field = reader.ReadField();
                if (field.Number == 1 && field.WireType == 2)
                {
                    byte[] body = reader.ReadBytes();
                    return System.Text.Encoding.UTF8.GetString(body, 0, body.Length);
                }

                reader.SkipField(field.WireType);
            }

            throw new ProtocolException("the plaintext carries no body");
        }

        /// <summary>The protobuf inside a sealed message's `version || protobuf || mac`.</summary>
        private static byte[] Shift(byte[] wire)
        {
            var message = new byte[wire.Length - 1 - SignalConstants.MacLength];
            Buffer.BlockCopy(wire, 1, message, 0, message.Length);
            return message;
        }

        /// <summary>
        /// A source that always returns the fixture's own ratchet key. A session that steps
        /// its ratchet draws one key per step, and the reference's bytes only come out if
        /// that draw is the key the reference drew.
        /// </summary>
        private sealed class FixedRandom : IRandomSource
        {
            private readonly byte[] _key;

            public FixedRandom(byte[] key)
            {
                _key = key;
            }

            public byte[] Bytes(int count)
            {
                if (_key == null || _key.Length != count)
                {
                    throw new ProtocolException("the fixture key is not the size the session asked for");
                }

                return _key;
            }
        }

        /// <summary>Where the two shapes of a session come from; see `SignalSessions`.</summary>
        private static byte[] FirstMessage()
        {
            return SignalSessions.FirstMessage();
        }
    }
}
